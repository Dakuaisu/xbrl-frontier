"""Draft of the README contamination statement (PRD section 4 "Contamination statement"; O-018; T-029).

Every number is read from a recorded file or config key at generation time; a figure that is not measured yet
(or whose file is absent) is printed as "__" with what will fill it. Nothing is estimated. Writes
docs/drafts/contamination_statement_draft.md (regenerate after each new measurement).
"""
import csv
import json
from pathlib import Path

from xbrl_frontier import config

D = config.REPO_ROOT / "data"
OUT = config.DOCS / "drafts" / "contamination_statement_draft.md"


def _j(path: Path):
    return json.loads(path.read_text()) if path.exists() else None


def run1_trained() -> str | None:
    """Trained-instance line from run 1's latest run.json (final, else the newest session file); None before run 1 exists."""
    d = D / "phase2" / "kaggle" / "run-Qwen3-1.7B-s1"
    files = [d / "run.json"] if (d / "run.json").exists() else sorted(d.glob("session*_run.json"))
    if not files:
        return None
    r = json.loads(files[-1].read_text())
    return (f"run 1 trains on {r['trained_instances']:,} of {r['corpus_size']:,} instances; {r['skipped_over_max_seq_len']:,} exceed "
            f"`training.kaggle.max_seq_len_tokens` ({r['max_seq_len']:,}) and are skipped")


def _blank(what: str) -> str:
    return f"__ (not yet measured: {what})"


def build() -> str:
    man = list(csv.DictReader(open(config.docs_path(config.get("pins.eval_manifest")))))
    rep, ser = _j(D / "manifest_work" / "report.json"), _j(D / "manifest_work" / "serializer_rebuild.json")
    sel, cor = _j(D / "train_selection_report.json"), _j(D / "corpus_report.json")
    pool, final = _j(D / "contamination_audit" / "summary_pool.json"), _j(D / "contamination_audit" / "summary_final.json")
    par_pool, par_s = _j(D / "format_parity_report.json"), _j(D / "format_parity_report_sampled.json")
    fr = _j(D / "fresh_selection_report.json")
    fresh_rows = [l.split("\t") for l in open(config.docs_path(config.get("pins.fresh_accessions"))) if not l.startswith("#")]
    relaxed = sum(1 for r in fresh_rows[1:] if r[fresh_rows[0].index("fill")] == "relaxed") if fresh_rows else 0
    audit = _j(D / "label_audit" / "audit_result.json")
    c = config.get("contamination")
    companies = len({m["cik"] for m in man})
    dates = sorted(m["filing_date"] for m in man)
    L = []
    L.append("## Contamination statement (draft, generated by scripts/contamination_statement.py)\n")
    L.append("**Evaluation set.** FinTagging FinNI-eval-v2 at revision "
             f"`{config.get('pins.eval_finni.hf_revision')}` ({config.get('pins.eval_finni.rows_expected'):,} rows). "
             f"Its filings were recovered from EDGAR: {companies} of {c['eval_manifest_required_recovered']} registrants "
             f"(`contamination.eval_manifest_required_recovered` NOT MET; O-010), {len(man)} filings dated {dates[0]} to {dates[-1]}. "
             + (f"Instances mapped to a filing: {ser['assignment_rate_raw']:.2%} raw / {ser['assignment_rate_dedup']:.2%} dedup with the "
                f"benchmark's own serializer (Phase 0 token matcher: {ser['phase0_token_matcher']['assignment_rate_raw']:.2%} / "
                f"{ser['phase0_token_matcher']['assignment_rate_dedup']:.2%}); the unassigned stratum is excluded from the frontier sample."
                if ser else _blank("instance assignment")) + "\n")
    L.append("**Training data exclusion.** Training filings are 10-K/10-Q filed "
             f"{config.get('training.accession_selection.filing_date_min')} to {c['train_filing_date_max']} (strictly before the eval "
             f"window), from CIKs outside {', '.join(c['exclude_ciks_from'])}"
             + (f" ({sel['excluded_ciks_total']} CIKs excluded; the last file lists the {sel['excluded_cik_counts'].get('data/eval_cik_candidates_unconfirmed.txt', 0)} "
                "FTS-resolved but unconfirmed CIKs, excluded conservatively, T-008)" if sel else "")
             + ". One filing per company.\n")
    if pool and final:
        L.append(f"**Overlap audit.** Every training instance eligible for the corpus ({pool['audited']:,}) was checked against every "
                 f"eval context ({pool['eval_contexts']:,} distinct) with {pool['ngram_n']}-gram overlap (lm-eval-harness style) and MinHash "
                 f"({pool['minhash']['num_perm']} permutations, Jaccard >= {pool['minhash']['threshold']}). Flagged: {pool['flagged']:,} "
                 f"({pool['flagged'] / pool['audited']:.1%}; {pool.get('flagged_pos', 0):,} positives, {pool.get('flagged_neg', 0):,} negatives; "
                 f"{pool.get('flagged::ngram', 0):,} by n-gram only, {pool.get('flagged::both', 0):,} by both, {pool.get('flagged::minhash', 0):,} by "
                 f"MinHash only), all removed. Re-audit of the final corpus: {final['flagged']} flagged of {final['audited']:,}.\n")
    else:
        L.append(_blank("overlap audit") + "\n")
    if cor:
        t, d = cor["splits"]["train"], cor["splits"]["dev"]
        tr = run1_trained()
        L.append(f"**Corpus size.** Train {t['used']:,} instances (cap {t['cap']:,} not reached after decontamination, O-016); dev "
                 f"{d['used']:,} (cap {d['cap']:,} not reached after decontamination, O-016)." + (f" {tr[0].upper()}{tr[1:]}." if tr else "") + "\n")
    if par_pool and par_s:
        a, b, e = par_pool["train_positives"], par_s["train_positives"], par_s["eval_positives"]
        L.append(f"**What decontamination removed (O-017).** Training positives before the audit: table share {a['table_share']:.3f}, median "
                 f"{a['context_tokens_quantiles']['0.5']} tokens; after: {b['table_share']:.3f}, median {b['context_tokens_quantiles']['0.5']} "
                 f"(eval: {e['table_share']:.3f}, {e['context_tokens_quantiles']['0.5']}). Long tables share more 13-grams with eval "
                 "boilerplate, so the corpus is somewhat shorter and less table-heavy than the eval; this is reported next to the table slice.\n")
    cut = config.get("contamination.frontier_arm_cutoffs")
    L.append("**Model cutoffs vs eval dates.** Frontier arms: " + "; ".join(f"`{k}` {v['cutoff']}" for k, v in cut.items())
             + f" (vendor docs). Eval filings end {dates[-1]}, before every arm's cutoff, so the arms may have seen them. Student base models "
             + "(Qwen3-0.6B/1.7B): cutoff __ (not published by the vendor). Encoder (SEC-BERT): pretraining corpus period __ (not verified).\n")
    if fr:
        unf = ", ".join(f"{k} ({v})" for k, v in fr["unfilled_quota"].items())
        L.append(f"**Fresh slice.** {fr['accepted']} 10-K filings dated {fr['filing_dates'][0]} to {fr['filing_dates'][1]} "
                 f"(after `fresh_slice_filing_date_min` = {c['fresh_slice_filing_date_min']}, the latest arm cutoff + 1 day), from CIKs outside "
                 f"the eval manifest, the exclusion files and the training list; {relaxed} of them filled outside their stratum "
                 f"(`fill=relaxed`) because these cells could not be filled in the window: {unf} (December year-end filers file no 10-K "
                 f"in it; T-015). {fr['instances_file']['instances']:,} instances (sha256 `{fr['instances_file']['sha256'][:16]}...`).\n")
    L.append("**Fresh-slice gaps.** Student FinTagging-minus-fresh F1 gap: " + _blank("student fresh-slice run") + "; control arm "
             f"(`{config.get('frontier.fresh_slice_control_arm')}`) gap: " + _blank("control run (O-022)") + "; difference: "
             + _blank("both gaps") + ". The student gap is gated by `gates.fresh_slice_f1_gap_max`.\n")
    L.append("**Label noise.** Estimated auto-label error rate: "
             + (f"{audit['label_audit_error_rate']:.3f} (self-agreement {audit['self_agreement']:.2f})" if audit else _blank("label audit, two passes"))
             + ".\n")
    L.append("**Caveat.** Public iXBRL HTML carries the labels inline: any model that saw these filings during pretraining may have seen "
             "the tags, which no overlap audit against the eval contexts can rule out.\n")
    return "\n".join(L)


def main() -> None:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(build())
    print(OUT.read_text())


if __name__ == "__main__":
    main()
